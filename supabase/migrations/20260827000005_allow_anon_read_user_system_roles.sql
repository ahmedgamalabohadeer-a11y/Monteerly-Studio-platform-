-- سياسة تسمح لـ anon key بالقراءة
-- تحذير: هذه للاختبار فقط — يجب إزالتها في الإنتاج
CREATE POLICY "Allow anon to read user_system_roles (TEMP)"
  ON public.user_system_roles
  FOR SELECT
  TO anon
  USING (true);
